FREQ = {w: len(WORDS) - i for i, w in enumerate(WORDS)}

def suggest(prefix, k=3):
    if not prefix: return ["привет", "да", "нет"][:k]
    c = [w for w in WORDS if w.startswith(prefix) and w != prefix]
    return (c + [""] * k)[:k]
